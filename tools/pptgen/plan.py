def _cell(value):
    return str(value).replace("&", "&amp;").replace("<", "&lt;").replace(
        ">", "&gt;").replace("|", "&#124;").replace("\n", "<br>")


def render_contracts(report, metadata):
    stages = report["stages"]
    next_stage = report["next_stage"]
    deck = metadata.get(4, {}).get("deck", {}) if isinstance(metadata.get(4), dict) else {}
    preset = deck.get("preset", "rvlab") if isinstance(deck, dict) else "rvlab"
    budget = deck.get("budget", "standard") if isinstance(deck, dict) else "standard"
    lines = [MARKER, "# 합의와 승인 관계도", "",
             f"Task: `{report['task_id']}` · Preset: `{preset}` · Budget: `{budget}`", "",
             "이 파일은 생성 시점의 상태다. 수정·승인 뒤 `uv run pptgen plan tasks/" + report["task_id"] + "`로 갱신한다.",
             "승인 판정의 원본은 각 문서의 메타데이터와 `pptgen status`다. 이 문서를 편집해도 승인되지 않는다.", "",
             f"내용 승인: **{'완료' if report['content_approved'] else '미완료'}**. 디자인·렌더 QA 및 4x 크리틱 검수는 별도다.",
             f"다음 검토: **Stage {next_stage} — `{report['next_document']}`**" if next_stage else
             "다음 작업: 빌드·렌더 QA, 4x 크리틱 검수(`audit`)와 미리보기 확인(이 문서는 QA 완료를 판정하지 않는다).", "",
             "```mermaid", "flowchart TD", '  SRC["sources/ · 원자료"]',
             '  FIG["figures/ · 그림"]']
    for item, title in zip(stages, TITLES):
        n = item["stage"]
        lines.append(f'  S{n}["Stage {n} · {title}<br/>{item["file"]}<br/>{STATES[item["effective_status"]]}"]')
    for n in range(1, 5):
        lines.append(f"  SRC --> S{n}")
        lines.extend(f"  S{prior} --> S{n}" for prior in range(1, n))
    lines += ["  FIG --> S4", '  S4 -. "내용 승인 후 제작 QA" .-> OUT["PPTX · PDF · 미리보기"]',
              "```", "", "화살표는 승인 의존 관계다. 상위 입력이 바뀌면 연결된 하위 승인도 다시 확인한다.", "",
              "| 단계 | 합의 대상 | 원본 | 현재 상태 |", "| --- | --- | --- | --- |"]
    for item, title in zip(stages, TITLES):
        link = "../slides.md" if item["stage"] == 4 else Path(item["file"]).name
        lines.append(f"| {item['stage']} | {title} | [{item['file']}]({link}) | {STATES[item['effective_status']]} |")
    for item in stages:
        lines += ["", f"## Stage {item['stage']} — {TITLES[item['stage'] - 1]}", ""]
        if item.get("review_hash"):
            lines += [f"검토 해시 (`review_hash`): `{item['review_hash']}`", ""]
        review = metadata.get(item["stage"], {}).get("review", {})
        labels = {"audience": "청중", "purpose": "목적", "key_evidence": "핵심 근거",
                  "success_criteria": "성공 기준", "constraints": "제약", "topic": "주제",
                  "key_message": "핵심 메시지", "storyline": "스토리라인",
                  "duration_minutes": "발표 시간(분)", "language": "발표 언어"}
        if isinstance(review, dict):
            for key, label in labels.items():
                if key in review:
                    value = review[key]
                    lines.append(f"- {label}: {_cell(' / '.join(map(str, value)) if isinstance(value, list) else value)}")
            slides = review.get("slides")
            if isinstance(slides, list):
                lines += ["", "| ID | 섹션 | 토픽 | 핵심 문장 | 근거 | 초 | 그림 계획 |",
                          "| --- | --- | --- | --- | --- | --- | --- |"]
                for slide in slides:
                    if isinstance(slide, dict):
                        lines.append("| " + " | ".join(_cell(slide.get(k, "")) for k in
                                     ("id", "section", "topic", "headline", "evidence", "seconds", "figure")) + " |")
                lines.append("")
        for issue in item["issues"]:
            lines.append(f"- 확인할 문제: {_cell(issue)}")
        for warning in item.get("warnings", []):
            lines.append(f"- 권고·변경 보고: {_cell(warning)}")
        for assumption in item.get("assumptions", []):
            lines.append(f"- 가정: {_cell(assumption)}")
        for entry in item.get("open_items", []):
            lines.append(f"- 미해결 ({'승인 차단' if entry['blocking'] else '참고'}): {_cell(entry['description'])}")
    lines += ["", "진행 상태 및 Truth 모델: [PROGRESS.md](PROGRESS.md) · 수정 요청과 처리 이력: [revisions.md](revisions.md). 요청을 승인으로 해석하지 않는다.", ""]
    return "\n".join(lines)


def write_plan(task):
    task = Path(task)
    report = status(task)
    metadata = {item["stage"]: read_document(task / item["file"], task.name, item["stage"]).metadata
                for item in report["stages"] if "content_hash" in item}
    folder = task / "plan"
    contracts, revisions, progress = folder / "contracts.md", folder / "revisions.md", folder / "PROGRESS.md"
    # Reject links and unowned files before writing any document.
    for path in (folder, contracts, revisions, progress):
        if path.is_symlink():
            raise StateError(f"Plan path cannot be a symlink: {path.name}")
    for path in (contracts, revisions, progress):
        if path.exists() and not path.is_file():
            raise StateError(f"Expected plan file: {path.name}")
    if contracts.exists() and not contracts.read_text(encoding="utf-8").startswith(MARKER + "\n"):
        raise StateError("plan/contracts.md is not generated by rvppt; preserve or rename it first")
    folder.mkdir(exist_ok=True)
    if not revisions.exists():
        with revisions.open("x", encoding="utf-8", newline="\n") as output:
            output.write(REVISION_LOG)
    if not progress.exists():
        deck = metadata.get(4, {}).get("deck", {}) if isinstance(metadata.get(4), dict) else {}
        preset = deck.get("preset", "rvlab") if isinstance(deck, dict) else "rvlab"
        budget = deck.get("budget", "standard") if isinstance(deck, dict) else "standard"
        initial_progress = PROGRESS_LOG.replace("`standard`", f"`{budget}`", 1).replace("`rvlab`", f"`{preset}`", 1)
        with progress.open("x", encoding="utf-8", newline="\n") as output:
            output.write(initial_progress)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n", dir=folder,
                                         prefix=".rvppt-plan-", suffix=".tmp", delete=False) as output:
            temporary = Path(output.name)
            output.write(render_contracts(report, metadata))
        temporary.replace(contracts)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    return {"task_id": report["task_id"], "contracts": str(contracts), "revisions": str(revisions),
            "progress": str(progress), "next_stage": report["next_stage"], "content_approved": report["content_approved"]}
